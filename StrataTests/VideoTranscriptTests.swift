/// A site that answers with a fixed transcript and counts its calls.
private final class CannedSource: TranscriptSource, @unchecked Sendable {
    let result: Result<VideoTranscript, YouTubeError>
    private(set) var count = 0
    init(_ result: Result<VideoTranscript, YouTubeError>) { self.result = result }
    var name: String { "YouTube" }
    func videoID(in url: URL) -> String? { YouTubeURL.videoID(in: url) }
    func canonicalURL(videoID: String) -> String { "https://www.youtube.com/watch?v=" + videoID }
    func transcript(videoID: String, language: String?) async throws -> VideoTranscript {
        count += 1
        return try result.get()
    }
}

