private final class Fixtures {
    static func data(_ name: String, _ ext: String) throws -> Data {
        let url = try #require(Bundle(for: Fixtures.self).url(forResource: name, withExtension: ext))
        return try Data(contentsOf: url)
    }

    static func player(_ name: String) throws -> YouTubePlayer { try YouTubePlayer(json: data("youtube-player-" + name, "json")) }
}

/// Answers the player request with a fixture per client (or an error), and every track with `track`.
private final class FakeYouTube: YouTubeTransport, @unchecked Sendable {
    var players: [String: Result<Data, YouTubeError>]
    var body: (URL) throws -> Data
    private let lock = NSLock()
    private var log: [String] = []

    init(players: [String: Result<Data, YouTubeError>], track: @escaping (URL) throws -> Data) {
        self.players = players
        self.body = track
    }

    var calls: [String] { lock.withLock { log } }

    func player(videoID: String, client: InnerTubeClient) async throws -> Data {
        lock.withLock { log.append("player " + client.name) }
        return try (players[client.name] ?? .failure(.http(500))).get()
    }

    func track(_ url: URL) async throws -> Data {
        lock.withLock { log.append("track " + url.absoluteString) }
        return try body(url)
    }
}

private func source(_ fake: FakeYouTube, page: YouTubeTranscriptSource.PageSession? = nil) -> YouTubeTranscriptSource {
    YouTubeTranscriptSource(transport: fake, clients: InnerTubeClient.chain, pageSession: page)
}

private func query(_ url: URL, _ name: String) -> String? {
    URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems?.first { $0.name == name }?.value
}

