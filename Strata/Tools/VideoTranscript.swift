import Foundation

// `video_transcript`: a video's transcript from its captions, read on the device. Each video site is a
// `TranscriptSource`; YouTube is the only one for now.

/// One caption cue: when it starts (seconds into the video) and its text.
struct CaptionCue: Sendable, Equatable {
    var start: Double
    var text: String
}

/// A video's captions and what the result says about them.
struct VideoTranscript: Sendable, Equatable {
    var title: String
    var channel: String
    /// Seconds; nil when the site doesn't say (a live stream).
    var duration: Int?
    /// The link the video is listed under as a source.
    var url: String
    /// The captions' language, as a name ("Korean") and a code ("ko").
    var language: String
    var languageCode: String
    /// Generated by speech recognition rather than uploaded by the channel.
    var isAutoGenerated: Bool
    /// Machine-translated by the site from this language's captions.
    var translatedFrom: String?
    /// Told to the model under the header: the language asked for is missing, and what exists instead.
    var note: String?
    var cues: [CaptionCue]
    /// A translation was asked for and the site wouldn't make it (`note` says so); another way to ask may work.
    var translationFailed = false
}

/// A video site `video_transcript` can read.
protocol TranscriptSource: Sendable {
    /// The site's name in messages ("YouTube").
    var name: String { get }
    /// The video's id when `url` is one of this site's video links, else nil.
    func videoID(in url: URL) -> String?
    /// The link a video is listed under as a source.
    func canonicalURL(videoID: String) -> String
    /// The video's captions, in `language` (a code like "ko") when given and available.
    func transcript(videoID: String, language: String?) async throws -> VideoTranscript
}

/// Turns cues into what the model reads: paragraphs of about half a minute, each led by its timestamp.
enum TranscriptFormatter {
    /// A paragraph ends at the first sentence end after this many seconds...
    static let paragraphSeconds: Double = 20
    /// ...and at the next cue after this many, sentence end or not.
    static let maxParagraphSeconds: Double = 30

    /// `[mm:ss]`, or `[h:mm:ss]` in a video an hour long or more (`hours`).
    static func timestamp(_ seconds: Double, hours: Bool) -> String {
        let total = max(0, Int(seconds))
        let (h, m, s) = (total / 3600, total / 60 % 60, total % 60)
        if hours || h > 0 { return String(format: "[%d:%02d:%02d]", h, m, s) }
        return String(format: "[%02d:%02d]", m, s)
    }

    /// "2:18", "1:02:03".
    static func duration(_ seconds: Int) -> String {
        let (h, m, s) = (seconds / 3600, seconds / 60 % 60, seconds % 60)
        return h > 0 ? String(format: "%d:%02d:%02d", h, m, s) : String(format: "%d:%02d", m, s)
    }

    /// The transcript's text: paragraphs separated by blank lines, cues joined with spaces.
    static func body(_ cues: [CaptionCue], duration: Int?) -> String {
        let hours = (duration ?? 0) >= 3600 || (cues.last?.start ?? 0) >= 3600
        var paragraphs: [String] = []
        var start: Double?
        var text = ""
        func flush() {
            if let start, !text.isEmpty { paragraphs.append(timestamp(start, hours: hours) + " " + text) }
            start = nil
            text = ""
        }
        for cue in cues {
            if let begun = start {
                let elapsed = cue.start - begun
                if elapsed >= maxParagraphSeconds || (elapsed >= paragraphSeconds && endsSentence(text)) { flush() }
            }
            if start == nil { start = cue.start }
            text += text.isEmpty ? cue.text : " " + cue.text
        }
        flush()
        return paragraphs.joined(separator: "\n\n")
    }

    private static func endsSentence(_ text: String) -> Bool {
        guard let last = text.last else { return false }
        return ".!?。！？…".contains(last) || text.hasSuffix(".\"") || text.hasSuffix("?\"")
    }

    /// The lines above the transcript: channel, length, which captions these are, and the note.
    static func header(_ transcript: VideoTranscript) -> String {
        var lines: [String] = []
        if !transcript.channel.isEmpty { lines.append("Channel: \(transcript.channel)") }
        if let duration = transcript.duration, duration > 0 { lines.append("Duration: \(Self.duration(duration))") }
        var captions = "Captions: \(transcript.language) (\(transcript.languageCode))"
        if let from = transcript.translatedFrom {
            captions += ", machine-translated by YouTube from \(from)"
        } else {
            captions += transcript.isAutoGenerated ? ", auto-generated" : ", uploaded by the channel"
        }
        lines.append(captions)
        if let note = transcript.note { lines.append("Note: \(note)") }
        return lines.joined(separator: "\n")
    }
}

/// Transcripts already read, so continuation calls (`offset`) do not fetch them again (about 10 minutes).
final class TranscriptCache: @unchecked Sendable {
    static let shared = TranscriptCache()
    var timeToLive: TimeInterval = 600
    var capacity = 16

    struct Entry: Sendable { var transcript: VideoTranscript; var body: String }

    private let lock = NSLock()
    private var entries: [String: (entry: Entry, stored: Date)] = [:]

    static func key(site: String, videoID: String, language: String?) -> String {
        "\(site):\(videoID):\(language?.lowercased() ?? "")"
    }

    func entry(for key: String, now: Date = .now) -> Entry? {
        lock.withLock {
            guard let e = entries[key], now.timeIntervalSince(e.stored) < timeToLive else { return nil }
            return e.entry
        }
    }

    func store(_ entry: Entry, for key: String, now: Date = .now) {
        lock.withLock {
            entries[key] = (entry, now)
            if entries.count > capacity, let oldest = entries.min(by: { $0.value.stored < $1.value.stored })?.key { entries[oldest] = nil }
        }
    }

    func removeAll() { lock.withLock { entries.removeAll() } }
}

/// `video_transcript(url, lang, offset)`: finds the site the link belongs to, reads the captions, and returns one slice
/// of the transcript, paged like `web_fetch`.
struct VideoTranscriptTool {
    var sources: [any TranscriptSource] = [YouTubeTranscriptSource()]
    var cache: TranscriptCache = .shared
    /// Characters returned per call (Settings > Fetch length, as for `web_fetch`).
    var limit: Int = AppSettings.currentFetchLength
    /// The whole call, including a second try in the hidden browser.
    var deadline: Duration = FetchTimeouts.current.overall + FetchTimeouts.current.load

    static let unsupportedSite = "Error: video_transcript only supports YouTube videos for now (youtube.com and youtu.be links, including Shorts and live streams). For other pages, use web_fetch."

    /// A link as the user may paste it: without a scheme, or as a bare YouTube video id.
    static func url(from raw: String) -> URL? {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if YouTubeURL.isVideoID(trimmed) { return URL(string: "https://www.youtube.com/watch?v=" + trimmed) }
        if trimmed.contains("://") { return URL(string: trimmed) }
        return URL(string: "https://" + trimmed)
    }

    func run(urlString: String, language: String? = nil, offset: Int = 0) async -> ToolOutput {
        guard let url = Self.url(from: urlString), url.host() != nil else {
            return ToolOutput(text: "Error: \"\(urlString)\" is not a video link.", isError: true)
        }
        guard offset >= 0 else {
            return ToolOutput(text: "Error: offset must be zero or a positive character offset.", isError: true)
        }
        guard let (source, id) = sources.lazy.compactMap({ source in source.videoID(in: url).map { (source, $0) } }).first else {
            if YouTubeURL.isYouTube(url) {
                return ToolOutput(text: "Error: this YouTube link doesn't point at a video. Pass a video link like https://www.youtube.com/watch?v=VIDEO_ID or https://youtu.be/VIDEO_ID.", isError: true)
            }
            return ToolOutput(text: Self.unsupportedSite, isError: true)
        }
        let lang = language?.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            .replacingOccurrences(of: "_", with: "-").nonEmpty
        let key = TranscriptCache.key(site: source.name, videoID: id, language: lang)
        let entry: TranscriptCache.Entry
        if let cached = cache.entry(for: key) {
            entry = cached
        } else {
            do {
                let transcript = try await Deadline.run(deadline) { try await source.transcript(videoID: id, language: lang) }
                entry = TranscriptCache.Entry(transcript: transcript, body: TranscriptFormatter.body(transcript.cues, duration: transcript.duration))
            } catch is CancellationError {
                return ToolOutput(text: "Error: cancelled.", isError: true)
            } catch WebToolError.timeout {
                return ToolOutput(text: "Error: reading the captions took longer than \(FetchTimeouts.seconds(deadline)).", isError: true)
            } catch {
                return ToolOutput(text: "Error: \(error.localizedDescription)", isError: true)
            }
            cache.store(entry, for: key)
        }
        return Self.output(entry, offset: offset, limit: limit)
    }

    /// One slice of the transcript with the footer `web_fetch` uses, its source the video.
    static func output(_ entry: TranscriptCache.Entry, offset: Int, limit: Int) -> ToolOutput {
        let transcript = entry.transcript
        switch PageSlicer.slice(entry.body, offset: offset, limit: limit, tool: ToolNames.videoTranscript, noun: "transcript") {
        case .offsetPastEnd(let off, let total):
            return ToolOutput(text: "Error: offset \(off) is past the end of the transcript (\(total) characters). Use an offset below \(total).", isError: true)
        case .slice(let body, let footer):
            let content = (offset == 0 ? TranscriptFormatter.header(transcript) + "\n\n" : "") + body + "\n\n" + footer
            let header = offset == 0 ? "Title: \(transcript.title)\nURL: \(transcript.url)\n\n" : "URL: \(transcript.url)\n\n"
            return ToolOutput(text: header + content,
                              sources: [SourceCandidate(title: transcript.title.isEmpty ? transcript.url : transcript.title,
                                                        url: transcript.url, content: content)])
        }
    }
}

private extension String {
    var nonEmpty: String? { isEmpty ? nil : self }
}
