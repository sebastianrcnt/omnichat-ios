import Foundation

// YouTube captions for `video_transcript`, read the way YouTube's own mobile apps read them: the InnerTube player
// endpoint (`youtubei/v1/player`) with an Android or iOS client context lists the caption tracks, and each track's
// `baseUrl` returns its cues. The watch page's own (web client) track URLs need a proof-of-origin token and come back
// empty, so they are not used. When YouTube answers with a bot check, the same requests are made again from a YouTube
// page in the hidden browser, which carries its cookies and visitor id.

// MARK: - Links

enum YouTubeURL {
    /// An 11-character video id.
    static func isVideoID(_ s: String) -> Bool {
        s.count == 11 && s.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "-" || $0 == "_") }
    }

    static func isYouTube(_ url: URL) -> Bool {
        guard let host = url.host(percentEncoded: false)?.lowercased() else { return false }
        return host == "youtu.be" || ["youtube.com", "youtube-nocookie.com"].contains { host == $0 || host.hasSuffix("." + $0) }
    }

    /// The video a link points at: `watch?v=`, `youtu.be/`, `/shorts/`, `/live/`, `/embed/` (and `/v/`, `/e/`), on any
    /// YouTube host (`m.`, `music.`, `www.`, youtube-nocookie.com). Other query parameters (`t=`, `si=`, `list=`) don't matter.
    static func videoID(in url: URL) -> String? {
        guard isYouTube(url), let host = url.host(percentEncoded: false)?.lowercased() else { return nil }
        let parts = url.path(percentEncoded: false).split(separator: "/").map(String.init)
        let id: String?
        if host == "youtu.be" {
            id = parts.first
        } else if parts.first == "watch" {
            id = URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems?.first { $0.name == "v" }?.value
                ?? parts.dropFirst().first
        } else if parts.count >= 2, ["shorts", "live", "embed", "v", "e"].contains(parts[0]) {
            id = parts[1]
        } else {
            id = nil
        }
        guard let id, isVideoID(id) else { return nil }
        return id
    }
}

// MARK: - Player response

/// A caption track the player lists.
struct CaptionTrack: Sendable, Equatable {
    var languageCode: String
    /// "Korean (auto-generated)", as YouTube names it in English.
    var name: String
    /// Speech recognition (`kind: asr`).
    var isAutoGenerated: Bool
    var baseURL: String
    var isTranslatable = false

    /// The language's name without YouTube's "(auto-generated)".
    var languageName: String {
        let trimmed = name.replacingOccurrences(of: " (auto-generated)", with: "").trimmingCharacters(in: .whitespaces)
        return trimmed.isEmpty ? languageCode : trimmed
    }

    /// "Korean (ko)", "English (en, auto-generated)".
    var listing: String { "\(languageName) (\(languageCode)\(isAutoGenerated ? ", auto-generated" : ""))" }
}

/// A language YouTube can translate captions into.
struct CaptionLanguage: Sendable, Equatable {
    var code: String
    var name: String
}

/// What the player endpoint says about a video, as far as captions go.
struct YouTubePlayer: Sendable, Equatable {
    var status: String
    var reason: String?
    var title: String
    var channel: String
    var duration: Int?
    var tracks: [CaptionTrack]
    var translationLanguages: [CaptionLanguage]
    /// The spoken language of the upload (not of an auto-dubbed audio track), when it can be told.
    var originalLanguage: String?
    /// The track YouTube would show by default.
    var defaultTrack: Int?

    private struct Response: Decodable {
        struct Playability: Decodable { var status: String?; var reason: String? }
        struct Details: Decodable { var title: String?; var author: String?; var lengthSeconds: String? }
        struct Text: Decodable {
            var simpleText: String?
            var runs: [Run]?
            struct Run: Decodable { var text: String? }
            var string: String { simpleText ?? runs?.compactMap(\.text).joined() ?? "" }
        }
        struct Captions: Decodable { var playerCaptionsTracklistRenderer: Tracklist? }
        struct Tracklist: Decodable {
            var captionTracks: [Track]?
            var audioTracks: [AudioTrack]?
            var translationLanguages: [Language]?
            var defaultAudioTrackIndex: Int?
        }
        struct Track: Decodable { var baseUrl: String?; var name: Text?; var languageCode: String?; var kind: String?; var isTranslatable: Bool? }
        struct AudioTrack: Decodable { var defaultCaptionTrackIndex: Int? }
        struct Language: Decodable { var languageCode: String?; var languageName: Text? }
        struct Streaming: Decodable { var adaptiveFormats: [Format]? }
        struct Format: Decodable { var audioTrack: FormatAudio? }
        struct FormatAudio: Decodable { var id: String?; var displayName: String?; var audioIsDefault: Bool?; var isAutoDubbed: Bool? }

        var playabilityStatus: Playability?
        var videoDetails: Details?
        var captions: Captions?
        var streamingData: Streaming?
    }

    init(status: String, reason: String? = nil, title: String = "", channel: String = "", duration: Int? = nil,
         tracks: [CaptionTrack] = [], translationLanguages: [CaptionLanguage] = [], originalLanguage: String? = nil,
         defaultTrack: Int? = nil) {
        self.status = status
        self.reason = reason
        self.title = title
        self.channel = channel
        self.duration = duration
        self.tracks = tracks
        self.translationLanguages = translationLanguages
        self.originalLanguage = originalLanguage
        self.defaultTrack = defaultTrack
    }

    init(json: Data) throws {
        guard let r = try? JSONDecoder().decode(Response.self, from: json) else { throw YouTubeError.badResponse }
        let list = r.captions?.playerCaptionsTracklistRenderer
        status = r.playabilityStatus?.status ?? ""
        reason = r.playabilityStatus?.reason
        title = r.videoDetails?.title ?? ""
        channel = r.videoDetails?.author ?? ""
        duration = r.videoDetails?.lengthSeconds.flatMap { Int($0) }.flatMap { $0 > 0 ? $0 : nil }
        tracks = (list?.captionTracks ?? []).compactMap { t in
            guard let url = t.baseUrl, let code = t.languageCode else { return nil }
            return CaptionTrack(languageCode: code, name: t.name?.string ?? code, isAutoGenerated: t.kind == "asr", baseURL: url,
                                isTranslatable: t.isTranslatable ?? false)
        }
        translationLanguages = (list?.translationLanguages ?? []).compactMap { l in
            l.languageCode.map { CaptionLanguage(code: $0, name: l.languageName?.string ?? $0) }
        }
        let audio = list?.audioTracks ?? []
        let index = list?.defaultAudioTrackIndex ?? 0
        defaultTrack = audio.indices.contains(index) ? audio[index].defaultCaptionTrackIndex : nil
        let formats = (r.streamingData?.adaptiveFormats ?? []).compactMap(\.audioTrack)
        originalLanguage = Self.originalLanguage(audio: formats.map { ($0.id ?? "", $0.displayName ?? "", $0.audioIsDefault ?? false, $0.isAutoDubbed ?? false) },
                                                 tracks: tracks)
    }

    /// A video with auto-dubbed audio lists an auto-generated track per audio language, so the speech-recognition
    /// track alone doesn't say what was spoken. The audio tracks do: the one that isn't dubbed (YouTube calls it
    /// "original") is the upload's. Their ids are "ko.4", "en-US.10": the language comes first.
    static func originalLanguage(audio: [(id: String, name: String, isDefault: Bool, dubbed: Bool)], tracks: [CaptionTrack]) -> String? {
        let own = audio.filter { !$0.dubbed && !$0.id.isEmpty }
        let pick = own.first { $0.name.lowercased().contains("original") } ?? own.first { $0.isDefault } ?? own.first
        if let pick, let language = pick.id.split(separator: ".").first, !language.isEmpty { return String(language) }
        let auto = tracks.filter(\.isAutoGenerated)
        return auto.count == 1 ? auto[0].languageCode : nil
    }

    /// Why there are no tracks: no captions, or no video to begin with.
    var failure: YouTubeError {
        let why = reason?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        switch status {
        case "OK": return .noCaptions(title: title)
        case "LOGIN_REQUIRED" where why.lowercased().contains("bot"): return .botCheck
        case "LOGIN_REQUIRED": return .signInRequired(why)
        case "": return .badResponse
        default: return .unavailable(why.isEmpty ? status : why)
        }
    }
}

// MARK: - Choosing a track

/// Which captions to read, and what to tell the model about the choice.
struct TrackChoice: Sendable, Equatable {
    var track: CaptionTrack
    /// Ask YouTube to translate the track into this language (`tlang`).
    var translateTo: CaptionLanguage?
    var note: String?
}

enum CaptionTrackPicker {
    /// "en-US" → "en". Chinese keeps its script ("zh-Hant"), which matters for reading.
    static func base(_ code: String) -> String {
        let lower = code.lowercased()
        if lower.hasPrefix("zh-han") { return lower }
        return String(lower.split(separator: "-").first ?? Substring(lower))
    }

    static func matches(_ code: String, _ wanted: String) -> Bool {
        code.lowercased() == wanted.lowercased() || base(code) == base(wanted)
    }

    /// With `language`: its uploaded captions, else its auto-generated ones, else YouTube's translation of the default
    /// track, else the default track with a note. Without: the original language's uploaded captions, then its
    /// auto-generated ones; then the track YouTube shows by default; then any uploaded track.
    static func pick(_ player: YouTubePlayer, language: String?) -> TrackChoice? {
        let tracks = player.tracks
        guard !tracks.isEmpty else { return nil }
        func find(_ wanted: String) -> CaptionTrack? {
            tracks.first { !$0.isAutoGenerated && $0.languageCode.lowercased() == wanted.lowercased() }
                ?? tracks.first { !$0.isAutoGenerated && matches($0.languageCode, wanted) }
                ?? tracks.first { $0.isAutoGenerated && matches($0.languageCode, wanted) }
        }
        let original = player.originalLanguage.flatMap(find)
        let fallback = original
            ?? player.defaultTrack.flatMap { tracks.indices.contains($0) ? tracks[$0] : nil }
            ?? tracks.first { !$0.isAutoGenerated }
            ?? tracks[0]
        guard let language else { return TrackChoice(track: fallback) }
        if let track = find(language) {
            // Auto-generated captions in another language than the original come from an auto-dubbed audio track.
            if track.isAutoGenerated, let spoken = player.originalLanguage, !matches(track.languageCode, spoken) {
                let name = tracks.first { matches($0.languageCode, spoken) }?.languageName ?? spoken
                return TrackChoice(track: track, note: "These captions transcribe YouTube's auto-dubbed \(track.languageName) audio, a machine translation of the original \(name).")
            }
            return TrackChoice(track: track)
        }
        let available = tracks.map(\.listing).joined(separator: ", ")
        if fallback.isTranslatable, let target = player.translationLanguages.first(where: { matches($0.code, language) }) {
            return TrackChoice(track: fallback, translateTo: target)
        }
        let name = player.translationLanguages.first { matches($0.code, language) }?.name ?? language
        return TrackChoice(track: fallback, note: "The video has no \(name) captions; these are the \(fallback.languageName) ones. Caption languages: \(available). Translate them yourself if needed.")
    }

    /// The track's URL for the JSON cue format, translated with `tlang` when asked. Relative `baseUrl`s resolve
    /// against `host`.
    static func url(for track: CaptionTrack, translateTo: String? = nil, host: String = "www.youtube.com") -> URL? {
        guard var comps = URLComponents(string: track.baseURL) else { return nil }
        if comps.host == nil { comps.scheme = "https"; comps.host = host }
        var items = (comps.percentEncodedQueryItems ?? []).filter { $0.name != "fmt" && $0.name != "tlang" }
        items.append(URLQueryItem(name: "fmt", value: "json3"))
        if let translateTo { items.append(URLQueryItem(name: "tlang", value: translateTo)) }
        comps.percentEncodedQueryItems = items
        return comps.url
    }
}

// MARK: - Cues

/// Reads a caption track: `json3` (what `CaptionTrackPicker.url` asks for), or the XML formats (`srv3`'s `<p t d>`,
/// the original `<text start dur>`) in case a track ignores `fmt`.
enum CaptionParser {
    static func cues(from data: Data) throws -> [CaptionCue] {
        let head = String(decoding: data.prefix(512), as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
        if head.isEmpty { throw YouTubeError.emptyTrack }
        let raw: [CaptionCue]
        if head.hasPrefix("{") {
            raw = try json3(data)
        } else if head.lowercased().hasPrefix("<!doctype html") || head.lowercased().hasPrefix("<html") {
            // Google's "Sorry..." page: too many requests from this network.
            throw YouTubeError.rateLimited
        } else if head.hasPrefix("<") {
            raw = try xml(data)
        } else {
            throw YouTubeError.badResponse
        }
        return clean(raw)
    }

    private struct JSON3: Decodable {
        struct Event: Decodable { var tStartMs: Double?; var segs: [Seg]? }
        struct Seg: Decodable { var utf8: String? }
        var events: [Event]?
    }

    static func json3(_ data: Data) throws -> [CaptionCue] {
        guard let doc = try? JSONDecoder().decode(JSON3.self, from: data) else { throw YouTubeError.badResponse }
        return (doc.events ?? []).compactMap { event in
            guard let segs = event.segs, let start = event.tStartMs else { return nil }
            return CaptionCue(start: start / 1000, text: segs.compactMap(\.utf8).joined())
        }
    }

    static func xml(_ data: Data) throws -> [CaptionCue] {
        let reader = XMLCueReader()
        let parser = XMLParser(data: data)
        parser.delegate = reader
        guard parser.parse() else { throw YouTubeError.badResponse }
        return reader.cues
    }

    /// Entities decoded, line breaks and runs of spaces collapsed; empty cues, cues that are only a sound tag
    /// ("[Music]", "[웃음]", "♪"), and a cue repeating the one before are dropped.
    static func clean(_ cues: [CaptionCue]) -> [CaptionCue] {
        var out: [CaptionCue] = []
        for cue in cues {
            let text = HTMLEntities.decode(cue.text).split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
            guard !text.isEmpty, !isSoundTag(text), text != out.last?.text else { continue }
            out.append(CaptionCue(start: cue.start, text: text))
        }
        return out
    }

    static func isSoundTag(_ text: String) -> Bool {
        text.range(of: #"^(\[[^\]]{0,30}\]|\([^)]{0,30}\)|[♪♫\s])+$"#, options: .regularExpression) != nil
    }
}

/// `<text start="1.2" dur="3">…</text>` (seconds) or `<p t="1200" d="3000">…<s>…</s></p>` (milliseconds).
private final class XMLCueReader: NSObject, XMLParserDelegate {
    var cues: [CaptionCue] = []
    private var start: Double?
    private var text = ""

    func parser(_ parser: XMLParser, didStartElement element: String, namespaceURI: String?, qualifiedName: String?,
                attributes: [String: String] = [:]) {
        switch element {
        case "text":
            start = attributes["start"].flatMap(Double.init)
            text = ""
        case "p":
            start = attributes["t"].flatMap(Double.init).map { $0 / 1000 }
            text = ""
        case "br":
            if start != nil { text += " " }
        default:
            break
        }
    }

    func parser(_ parser: XMLParser, foundCharacters string: String) {
        if start != nil { text += string }
    }

    func parser(_ parser: XMLParser, didEndElement element: String, namespaceURI: String?, qualifiedName: String?) {
        guard element == "text" || element == "p", let start else { return }
        cues.append(CaptionCue(start: start, text: text))
        self.start = nil
    }
}

/// HTML character references in caption text (the XML formats double-encode them: `&amp;#39;`).
enum HTMLEntities {
    static let named: [String: String] = ["amp": "&", "lt": "<", "gt": ">", "quot": "\"", "apos": "'", "nbsp": " "]

    static func decode(_ text: String) -> String {
        var current = text
        for _ in 0..<2 where current.contains("&") {
            current = decodeOnce(current)
        }
        return current
    }

    private static func decodeOnce(_ text: String) -> String {
        var out = ""
        var rest = text[...]
        while let amp = rest.firstIndex(of: "&") {
            out += rest[..<amp]
            let tail = rest[rest.index(after: amp)...]
            if let semi = tail.prefix(10).firstIndex(of: ";") {
                let name = String(tail[..<semi])
                let value: String?
                if name.hasPrefix("#x") || name.hasPrefix("#X") {
                    value = UInt32(name.dropFirst(2), radix: 16).flatMap(Unicode.Scalar.init).map { String(Character($0)) }
                } else if name.hasPrefix("#") {
                    value = UInt32(name.dropFirst()).flatMap(Unicode.Scalar.init).map { String(Character($0)) }
                } else {
                    value = named[name]
                }
                if let value {
                    out += value
                    rest = tail[tail.index(after: semi)...]
                    continue
                }
            }
            out += "&"
            rest = tail
        }
        return out + rest
    }
}

// MARK: - Errors

enum YouTubeError: Error, LocalizedError, Equatable {
    case noCaptions(title: String)
    case unavailable(String)
    case signInRequired(String)
    case botCheck
    case rateLimited
    case emptyTrack
    case http(Int)
    case network(String)
    case badResponse

    var errorDescription: String? {
        switch self {
        case .noCaptions(let title):
            let video = title.isEmpty ? "The video" : "The video \u{201C}\(title)\u{201D}"
            return "\(video) has no captions (none uploaded and no auto-generated ones), so there is no transcript to read."
        case .unavailable(let reason): return "YouTube says the video is unavailable: \(reason)"
        case .signInRequired(let reason):
            return "YouTube only shows this video to signed-in viewers (\(reason)), so its captions could not be read."
        case .botCheck: return "YouTube blocked the request: it asked to confirm this isn't a bot. Try again later."
        case .rateLimited: return "YouTube blocked the request: too many requests from this network (HTTP 429). Try again later."
        case .emptyTrack: return "YouTube returned an empty caption track."
        case .http(let status): return "YouTube answered HTTP \(status)."
        case .network(let message): return "could not reach YouTube: \(message)"
        case .badResponse: return "could not read YouTube's answer."
        }
    }

    /// Another client, or the hidden browser, may do better.
    var isRetryable: Bool {
        switch self {
        case .noCaptions, .unavailable, .signInRequired: false
        case .botCheck, .rateLimited, .emptyTrack, .http, .network, .badResponse: true
        }
    }
}

// MARK: - Requests

/// A client context for the player endpoint. Mobile clients get caption URLs that work without a proof-of-origin token.
struct InnerTubeClient: Sendable, Equatable {
    var name: String
    var version: String
    var userAgent: String
    /// More `context.client` fields (device and OS).
    var extra: [String: String] = [:]
    var sdkVersion: Int?

    static let android = InnerTubeClient(
        name: "ANDROID", version: "20.10.38", userAgent: "com.google.android.youtube/20.10.38 (Linux; U; Android 14) gzip",
        extra: ["osName": "Android", "osVersion": "14"], sdkVersion: 34)
    static let ios = InnerTubeClient(
        name: "IOS", version: "20.10.4", userAgent: "com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3_2 like Mac OS X;)",
        extra: ["deviceMake": "Apple", "deviceModel": "iPhone16,2", "osName": "iPhone", "osVersion": "18.3.2.22D82"])
    static let androidVR = InnerTubeClient(
        name: "ANDROID_VR", version: "1.65.10",
        userAgent: "com.google.android.apps.youtube.vr.oculus/1.65.10 (Linux; U; Android 12L; eureka-user Build/SQ3A.220605.009.A1) gzip",
        extra: ["deviceMake": "Oculus", "deviceModel": "Quest 3", "osName": "Android", "osVersion": "12L"], sdkVersion: 32)

    /// Tried in order; the next one after a bot check or a failed request.
    static let chain: [InnerTubeClient] = [.android, .ios, .androidVR]

    /// The player request's JSON body. `visitorData` is a page's visitor id (the hidden-browser try).
    func body(videoID: String, visitorData: String? = nil) -> Data {
        var client: [String: Any] = ["clientName": name, "clientVersion": version, "hl": "en"]
        for (key, value) in extra { client[key] = value }
        if let sdkVersion { client["androidSdkVersion"] = sdkVersion }
        if let visitorData { client["visitorData"] = visitorData }
        let body: [String: Any] = ["context": ["client": client], "videoId": videoID, "contentCheckOk": true, "racyCheckOk": true]
        return (try? JSONSerialization.data(withJSONObject: body, options: [.sortedKeys])) ?? Data()
    }
}

/// How the two requests reach YouTube: directly, or from a YouTube page in the hidden browser.
protocol YouTubeTransport: Sendable {
    /// The player endpoint's JSON for the video, as `client`.
    func player(videoID: String, client: InnerTubeClient) async throws -> Data
    /// A caption track's body.
    func track(_ url: URL) async throws -> Data
}

/// Plain HTTPS from the app, without cookies.
struct DirectYouTubeTransport: YouTubeTransport {
    static let playerURL = URL(string: "https://www.youtube.com/youtubei/v1/player?prettyPrint=false")!
    /// A transcript of several hours is a few megabytes of JSON.
    static let maxBytes = 24 * 1024 * 1024
    var timeout: TimeInterval = 15

    func player(videoID: String, client: InnerTubeClient) async throws -> Data {
        var request = URLRequest(url: Self.playerURL, timeoutInterval: timeout)
        request.httpMethod = "POST"
        request.httpBody = client.body(videoID: videoID)
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.setValue(client.userAgent, forHTTPHeaderField: "User-Agent")
        return try await send(request)
    }

    func track(_ url: URL) async throws -> Data {
        var request = URLRequest(url: url, timeoutInterval: timeout)
        request.setValue(HiddenWebView.userAgent, forHTTPHeaderField: "User-Agent")
        return try await send(request)
    }

    private func send(_ request: URLRequest) async throws -> Data {
        var request = request
        request.httpShouldHandleCookies = false
        request.setValue("en", forHTTPHeaderField: "Accept-Language")
        let data: Data, response: URLResponse
        do {
            (data, response) = try await LimitedDownload.data(for: request, limit: Self.maxBytes)
        } catch is CancellationError {
            throw CancellationError()
        } catch let error as URLError where error.code == .cancelled {
            throw CancellationError()
        } catch {
            throw YouTubeError.network(error.localizedDescription)
        }
        if let http = response as? HTTPURLResponse, !(200..<300).contains(http.statusCode) {
            throw http.statusCode == 429 ? YouTubeError.rateLimited : YouTubeError.http(http.statusCode)
        }
        return data
    }
}

/// The same requests, made with `fetch` from a YouTube watch page open in the hidden browser: they carry the shared
/// cookie store's YouTube cookies and the page's visitor id, which get past a bot check the cookieless ones hit.
final class PageYouTubeTransport: YouTubeTransport, @unchecked Sendable {
    private let page: HiddenWebView
    private let timeout: Duration

    @MainActor init(page: HiddenWebView, timeout: Duration = FetchTimeouts.current.script + .seconds(5)) {
        self.page = page
        self.timeout = timeout
    }

    func player(videoID: String, client: InnerTubeClient) async throws -> Data {
        let body = String(decoding: client.body(videoID: videoID), as: UTF8.self)
        return try await fetch("""
            const body = JSON.parse(\(Self.literal(body)));
            const visitor = (window.ytcfg && typeof ytcfg.get === "function" && ytcfg.get("VISITOR_DATA")) || "";
            if (visitor) body.context.client.visitorData = visitor;
            const r = await fetch("/youtubei/v1/player?prettyPrint=false", {method: "POST", credentials: "include",
              headers: {"Content-Type": "application/json"}, body: JSON.stringify(body)});
            return JSON.stringify({status: r.status, body: await r.text()});
            """)
    }

    func track(_ url: URL) async throws -> Data {
        // Same origin as the page, whichever YouTube host it ended up on.
        var comps = URLComponents(url: url, resolvingAgainstBaseURL: false)
        comps?.scheme = nil
        comps?.host = nil
        let path = comps?.string ?? url.absoluteString
        return try await fetch("""
            const r = await fetch(\(Self.literal(path)), {credentials: "include"});
            return JSON.stringify({status: r.status, body: await r.text()});
            """)
    }

    private struct Reply: Decodable { var status: Int; var body: String }

    private func fetch(_ script: String) async throws -> Data {
        let json: String
        do {
            json = try await page.callAsync(script, timeout: timeout)
        } catch WebToolError.timeout {
            throw YouTubeError.network("the request from the YouTube page timed out.")
        } catch let error as WebToolError {
            throw YouTubeError.network(error.localizedDescription)
        }
        guard let reply = try? JSONDecoder().decode(Reply.self, from: Data(json.utf8)) else { throw YouTubeError.badResponse }
        guard (200..<300).contains(reply.status) else {
            throw reply.status == 429 ? YouTubeError.rateLimited : YouTubeError.http(reply.status)
        }
        return Data(reply.body.utf8)
    }

    /// A JavaScript string literal (JSON-encoded).
    static func literal(_ s: String) -> String {
        (try? JSONSerialization.data(withJSONObject: [s], options: [.withoutEscapingSlashes]))
            .map { String(decoding: $0, as: UTF8.self) }
            .map { String($0.dropFirst().dropLast()) } ?? "\"\""
    }

    /// Opens the video's watch page in a pooled hidden web view and runs `work` with requests from it.
    @MainActor
    static func withPage(videoID: String, timeouts: FetchTimeouts = .current,
                         _ work: @escaping @Sendable (any YouTubeTransport) async throws -> VideoTranscript) async throws -> VideoTranscript {
        let pool = WebViewPool.shared
        let view = pool.acquire(reader: false)
        var reusable = false
        defer { pool.release(view, reusable: reusable) }
        do {
            try await view.load(URL(string: "https://m.youtube.com/watch?v=\(videoID)")!, timeout: timeouts.load)
        } catch WebToolError.timeout {
            // The page's scripts may never settle; its cookies and config are there long before.
        } catch let error as WebToolError {
            throw YouTubeError.network(error.localizedDescription)
        }
        guard let url = view.currentURL, YouTubeURL.isYouTube(url) else { throw YouTubeError.botCheck }
        let result = try await work(PageYouTubeTransport(page: view))
        reusable = true
        return result
    }
}

// MARK: - Source

/// YouTube for `video_transcript`.
struct YouTubeTranscriptSource: TranscriptSource {
    typealias PageSession = @Sendable (_ videoID: String,
                                       _ work: @escaping @Sendable (any YouTubeTransport) async throws -> VideoTranscript) async throws -> VideoTranscript

    var transport: any YouTubeTransport = DirectYouTubeTransport()
    var clients: [InnerTubeClient] = InnerTubeClient.chain
    /// The second try, after the direct requests met a bot check or failed: the same requests from a YouTube page in
    /// the hidden browser. Nil: none (tests).
    var pageSession: PageSession? = { videoID, work in try await PageYouTubeTransport.withPage(videoID: videoID, work) }

    var name: String { "YouTube" }

    func videoID(in url: URL) -> String? { YouTubeURL.videoID(in: url) }

    func canonicalURL(videoID: String) -> String { "https://www.youtube.com/watch?v=\(videoID)" }

    func transcript(videoID: String, language: String?) async throws -> VideoTranscript {
        let url = canonicalURL(videoID: videoID)
        let clients = clients
        do {
            let direct = try await Self.read(videoID: videoID, url: url, language: language, transport: transport, clients: clients)
            // YouTube translates captions only for a client with its cookies: the page has them.
            guard direct.translationFailed, let pageSession else { return direct }
            let translated = try? await pageSession(videoID) { page in
                try await Self.read(videoID: videoID, url: url, language: language, transport: page, clients: clients)
            }
            return translated.flatMap { $0.translationFailed ? nil : $0 } ?? direct
        } catch let first as YouTubeError where first.isRetryable {
            guard let pageSession else { throw first }
            do {
                return try await pageSession(videoID) { page in
                    try await Self.read(videoID: videoID, url: url, language: language, transport: page, clients: clients)
                }
            } catch let second as YouTubeError where !second.isRetryable {
                throw second
            } catch is CancellationError {
                throw CancellationError()
            } catch {
                throw first // the reason the direct try failed says more than the browser's
            }
        }
    }

    /// Asks each client in turn until one lists tracks and its track can be read. "No captions" and "unavailable" are
    /// final; a bot check or a failed request moves on to the next client.
    static func read(videoID: String, url: String, language: String?, transport: any YouTubeTransport,
                     clients: [InnerTubeClient]) async throws -> VideoTranscript {
        var last = YouTubeError.badResponse
        for client in clients {
            try Task.checkCancellation()
            do {
                let player = try YouTubePlayer(json: try await transport.player(videoID: videoID, client: client))
                guard let choice = CaptionTrackPicker.pick(player, language: language) else {
                    let failure = player.failure
                    if failure.isRetryable { last = failure; continue }
                    throw failure
                }
                return try await transcript(player, choice: choice, url: url, transport: transport)
            } catch let error as YouTubeError where error.isRetryable {
                last = error
            }
        }
        throw last
    }

    /// Reads the chosen track; a translation YouTube won't make falls back to the track itself, with a note.
    static func transcript(_ player: YouTubePlayer, choice: TrackChoice, url: String,
                           transport: any YouTubeTransport) async throws -> VideoTranscript {
        let track = choice.track
        var note = choice.note
        var translated: CaptionLanguage?
        var cues: [CaptionCue] = []
        if let target = choice.translateTo, let trackURL = CaptionTrackPicker.url(for: track, translateTo: target.code) {
            do {
                cues = try CaptionParser.cues(from: try await transport.track(trackURL))
                if !cues.isEmpty { translated = target }
            } catch is YouTubeError {
                // Read the original below.
            }
            if translated == nil {
                note = "YouTube could not translate the captions into \(target.name) right now, so these are the \(track.languageName) ones. Translate them yourself if needed."
            }
        }
        if translated == nil {
            guard let trackURL = CaptionTrackPicker.url(for: track) else { throw YouTubeError.badResponse }
            cues = try CaptionParser.cues(from: try await transport.track(trackURL))
        }
        guard !cues.isEmpty else { throw YouTubeError.emptyTrack }
        return VideoTranscript(title: player.title, channel: player.channel, duration: player.duration, url: url,
                               language: translated?.name ?? track.languageName, languageCode: translated?.code ?? track.languageCode,
                               isAutoGenerated: track.isAutoGenerated,
                               translatedFrom: translated == nil ? nil : track.listing, note: note, cues: cues,
                               translationFailed: choice.translateTo != nil && translated == nil)
    }
}
